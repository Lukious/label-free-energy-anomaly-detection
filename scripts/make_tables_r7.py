def t_trainseed(ts, det):
    """Post-hoc: backbone effect (PatchTST - HOW, both HoW scoring) per training seed."""
    if ts is None:
        return
    rows = []
    canon = det[det["model"].isin([PT, HW])]
    cb = canon.pivot_table(index=["building_id"], columns="model", values="f1")
    rows.append(("coupled 123--125 (canonical)", cb[PT].mean(), (cb[PT] - cb[HW])))
    for t, g in ts.groupby("train_seed"):
        b = g.pivot_table(index="building_id", columns="model", values="f1")
        rows.append((f"{t}", b[PT].mean(), b[PT] - b[HW]))
    from scipy import stats as st
    L = [r"\begin{tabular}{lcccc}", r"\toprule",
         r"Training seed & PatchTST F1 & PatchTST $-$ HOW & 95\% CI & $p_t$ \\", r"\midrule"]
    diffs = []
    for lab, f, d in rows:
        d = d.dropna()
        q = st.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
        L.append(f"{lab} & {f:.3f} & {d.mean():+.3f} & [{d.mean() - q:+.3f}, {d.mean() + q:+.3f}] & "
                 f"{fmtp(st.ttest_1samp(d, 0).pvalue)} \\\\")
        diffs.append(d.mean())
    L += [r"\bottomrule", r"\end{tabular}"]
    write("r7_trainseed.tex", L)
    d7 = [r for r in rows if r[0].startswith("7")][0][2].dropna()
    M("TSSevenDiff", float(d7.mean()))
    M("TSSevenP", float(st.ttest_1samp(d7, 0).pvalue))
    M("TSDiffMin", float(min(diffs))); M("TSDiffMax", float(max(diffs)))
    M("TSN", int(ts["train_seed"].nunique()))
    ps_ = [st.ttest_1samp(r[2].dropna(), 0).pvalue for r in rows]
    M("TSPMin", float(min(ps_)))
    allf = [r[1] for r in rows]
    M("TSFMin", float(min(allf))); M("TSFMax", float(max(allf)))


