def M(name, v):
    MACROS[name] = v


def load(name):
    p = os.path.join(MC, name)
    return pd.read_csv(p) if os.path.exists(p) else None


def ms(x, dec=2, pct=False):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    k = 100 if pct else 1
    if len(x) == 0:
        return "---"
    if len(x) == 1:
        return f"{k * x[0]:.{dec}f}"
    return f"{k * x.mean():.{dec}f} $\\pm$ {k * x.std(ddof=1):.{dec}f}"


def pct(v, dec=1):
    return f"{100 * v:+.{dec}f}\\%"


def write(name, lines):
    open(os.path.join(TAB, name), "w").write(
        "%% AUTO-GENERATED by scripts/make_tables_r7.py -- do not edit\n" + "\n".join(lines) + "\n")


def per_seed(det, cols):
    return det.groupby(["model", "seed"])[cols].mean().reset_index()


# ------------------------------------------------------------- detection
def t_detection(det):
    ps = per_seed(det, ["precision", "recall", "f1", "range_precision", "range_recall",
                        "range_f1", "false_alarm_rate"])
    L = [r"\begin{tabular}{lccccccc}", r"\toprule",
         r" & \multicolumn{3}{c}{Event level} & \multicolumn{3}{c}{Range (overlap) level} & \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
         r"Detector & P & R & F1 & P & R & F1 & NIAR (\%) \\", r"\midrule"]
    for gi, (gname, models) in enumerate(GROUPS):
        if gi:
            L.append(r"\midrule")
        L.append(rf"\multicolumn{{8}}{{l}}{{\emph{{{gname}}}}} \\")
        for m in models:
            g = ps[ps["model"] == m]
            if not len(g):
                continue
            L.append(f"{NICE[m]} & {ms(g['precision'])} & {ms(g['recall'])} & {ms(g['f1'], 3)} & "
                     f"{ms(g['range_precision'])} & {ms(g['range_recall'])} & {ms(g['range_f1'], 3)} & "
                     f"{ms(g['false_alarm_rate'], 2, pct=True)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("r7_detection.tex", L)
    for m, key in [(PT, "PT"), (PTG, "PTG"), (PTD, "PTD"), (HW, "HW"), (HWG, "HWG"), (HWD, "HWD"),
                   (PM, "PM"), (TW, "TW"), (SL, "SL"), ("IsolationForest(t)", "IF"),
                   ("OC-SVM(t)", "OCSVM"), ("Autoencoder(t)", "AE"), ("LSTM-AE(t)", "LSTMAE")]:
        g = ps[ps["model"] == m]
        if not len(g):
            continue
        for col, suf in [("f1", "F"), ("range_f1", "RF"), ("precision", "P"), ("recall", "R"),
                         ("false_alarm_rate", "NIAR"), ("range_recall", "RR")]:
            M(f"{key}{suf}", float(g[col].mean()))
        M(f"{key}Fsd", float(g["f1"].std(ddof=1)) if len(g) > 1 else 0.0)
    rr = ps[ps["model"].isin([PT, PTG, HW, HWG, PTD, HWD, TW, SL] + GEN)]["range_recall"]
    M("RangeRecallMin", float(ps.groupby("model")["range_recall"].mean().min()))
    M("RangeRecallMax", float(ps.groupby("model")["range_recall"].mean().max()))
    f = ps.groupby("model")["f1"].mean()
    M("FMinAll", float(f.min())); M("FMaxAll", float(f.max()))
    r = ps.groupby("model")["range_f1"].mean()
    M("RFMinAll", float(r.min())); M("RFMaxAll", float(r.max()))
    top = r.sort_values(ascending=False)
    M("FTopName", NICE[f.idxmax()].replace(r"\textbf{", "").replace("}", "").replace(" (ours)", ""))
    M("FTop", float(f.max()))
    M("RFTop", float(r.max()))
    M("RFTopNameB", NICE[r.idxmax()].replace(r"\textbf{", "").replace("}", "").replace(" (ours)", ""))
    M("RFTopName", NICE[top.index[0]].replace(r"\textbf{", "").replace("}", "") if top.index[0] != PT else "ours")
    M("NBuildings", int(det["building_id"].nunique()))
    M("NSites", int(det["building_id"].str.split("_").str[0].nunique()))
    M("NSiteMax", int(det.drop_duplicates("building_id")["building_id"].str.split("_").str[0].value_counts().max()))


