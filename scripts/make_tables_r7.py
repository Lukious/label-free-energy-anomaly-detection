def fmtp(p):
    if pd.isna(p):
        return "---"
    if p < 1e-4:
        return r"$<10^{-4}$"
    if p >= 0.001:
        return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


# ------------------------------------------------------------- per type
def type_recall(evd, models):
    g = evd[evd["model"].isin(models)].groupby(["model", "seed", "type"])["detected"].mean()
    return g.groupby(["model", "type"]).agg(["mean", "std"])


def t_granularity(det, evd):
    ps = per_seed(det, ["precision", "recall", "f1", "false_alarm_rate"])
    tr = type_recall(evd, [PT, PTD, PTG, HW, HWD, HWG])
    L = [r"\begin{tabular}{llcccccc}", r"\toprule",
         r"Backbone & Scoring & P & R & F1 & \multicolumn{3}{c}{Recall: spike / drift / schedule} \\",
         r"\midrule"]
    for bb, rows in [("PatchTST", [(PTG, "global"), (PTD, "HoD"), (PT, "HoW")]),
                     ("HOW profile", [(HWG, "global"), (HWD, "HoD"), (HW, "HoW")])]:
        for m, s in rows:
            g = ps[ps["model"] == m]
            rec = " & ".join(f"{tr.loc[(m, t), 'mean']:.2f}" for t in TYPES)
            L.append(f"{bb} & {s} & {ms(g['precision'])} & {ms(g['recall'])} & {ms(g['f1'], 3)} & {rec} \\\\")
        if bb == "PatchTST":
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("r7_granularity.tex", L)
    for m, key in [(PT, "PT"), (PTD, "PTD"), (PTG, "PTG"), (HW, "HW"), (HWD, "HWD"), (HWG, "HWG")]:
        for t in TYPES:
            M(f"{key}Rec{t.capitalize()}", float(tr.loc[(m, t), "mean"]))


def t_typesev(evd, orc, inj):
    d = evd[evd["model"].isin([PT, HW])].copy()
    d["delay_frac"] = d["delay_h"] / d["duration_h"]
    o = orc[orc["model"].isin([PT, HW])].copy()
    o["abs_err"] = (o["clip_kwh"] - o["true_kwh"]).abs() / o["true_kwh"]
    L = [r"\begin{tabular}{llrrcccccc}", r"\toprule",
         r" & & & & \multicolumn{2}{c}{Recall} & \multicolumn{2}{c}{Range recall} & Delay, ours & Oracle $|$err$|$ \\",
         r"\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
         r"Type & Severity & $n$ & dur.\ (h) & ours & HOW & ours & HOW & h (frac.) & ours / HOW \\",
         r"\midrule"]
    for t in TYPES:
        for s in (1, 2, 3):
            a = d[(d["model"] == PT) & (d["type"] == t) & (d["severity"] == s)]
            b = d[(d["model"] == HW) & (d["type"] == t) & (d["severity"] == s)]
            oa = o[(o["model"] == PT) & (o["type"] == t) & (o["severity"] == s)]["abs_err"]
            ob = o[(o["model"] == HW) & (o["type"] == t) & (o["severity"] == s)]["abs_err"]
            if not len(a):
                L.append(f"{t} & {SEVN[s]} & 0 & --- & & & & & & \\\\")
                continue
            dl = a.loc[a["detected"], "delay_h"]
            fr = a.loc[a["detected"], "delay_frac"]
            dtxt = f"{dl.median():.0f} ({fr.median():.2f})" if len(dl) else "---"
            L.append(f"{t} & {SEVN[s]} & {len(a)} & {a['duration_h'].median():.0f} & "
                     f"{a['detected'].mean():.2f} & {b['detected'].mean():.2f} & "
                     f"{a['range_cov'].mean():.2f} & {b['range_cov'].mean():.2f} & {dtxt} & "
                     f"{oa.median():.2f} / {ob.median():.2f} \\\\")
        L.append(r"\midrule" if t != "schedule" else "")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("r7_typesev.tex", L)
    pt = d[d["model"] == PT]
    for t in TYPES:
        a = pt[pt["type"] == t]
        M(f"N{t.capitalize()}", int(len(a)))
        M(f"DelayMed{t.capitalize()}", float(a.loc[a["detected"], "delay_h"].median()))
        M(f"DelayFrac{t.capitalize()}", float(a.loc[a["detected"], "delay_frac"].median()))
        M(f"Dur{t.capitalize()}", float(a["duration_h"].median()))
    M("NEventsTotal", int(len(pt)))
    M("NScheduleSubtle", int(len(pt[(pt["type"] == "schedule") & (pt["severity"] == 1)])))
    # injection realism (SM)
    if inj is not None:
        g = inj.groupby(["type", "severity"])
        L = [r"\begin{tabular}{llrrrrrr}", r"\toprule",
             r"Type & Severity & $n$ & dur.\ (h) & mean add / resid.\ sd & peak add / resid.\ sd & mean add / median load & excess / test energy \\",
             r"\midrule"]
        for (t, s), x in g:
            L.append(f"{t} & {SEVN[s]} & {len(x)} & {x['duration_h'].median():.0f} & "
                     f"{x['mean_add_over_resid_sd'].median():.2f} & {x['peak_add_over_resid_sd'].median():.2f} & "
                     f"{100 * x['mean_add_over_median_load'].median():.1f}\\% & "
                     f"{100 * x['excess_over_test_energy'].median():.2f}\\% \\\\")
        L += [r"\bottomrule", r"\end{tabular}"]
        write("r7_injection.tex", L)
        sch = inj[inj["type"] == "schedule"]
        M("SchedAddSdMed", float(sch["mean_add_over_resid_sd"].median()))
        M("SchedExcessPctMax", float(100 * sch.groupby("severity")["excess_over_test_energy"].median().max()))
        sp = inj[inj["type"] == "spike"]
        M("SpikeAddSdMed", float(sp["mean_add_over_resid_sd"].median()))
        dr = inj[inj["type"] == "drift"]
        M("DriftAddSdMed", float(dr["mean_add_over_resid_sd"].median()))


def t_transfer(det):
    models = [PT, PTG, HW, HWG, TW, SL] + GEN
    rng = np.random.default_rng(7)
    L = [r"\begin{tabular}{lcc}", r"\toprule",
         r"Detector & Seen offices ($n$=24) & Unseen types ($n$=17) \\", r"\midrule"]
    bl = det.groupby(["model", "building_id", "seen"])["f1"].mean().reset_index()
    for m in models:
        cells = []
        for seen in (True, False):
            x = bl[(bl["model"] == m) & (bl["seen"] == seen)]["f1"].dropna().to_numpy()
            bs = [x[rng.integers(0, len(x), len(x))].mean() for _ in range(4000)]
            cells.append(f"{x.mean():.2f} [{np.percentile(bs, 2.5):.2f}, {np.percentile(bs, 97.5):.2f}]")
        L.append(f"{NICE[m]} & {cells[0]} & {cells[1]} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("r7_transfer.tex", L)
    for m, key in [(PT, "PT"), (HW, "HW")]:
        for seen, s in [(True, "Seen"), (False, "Unseen")]:
            M(f"{key}F{s}", float(bl[(bl["model"] == m) & (bl["seen"] == seen)]["f1"].mean()))
    # buildings where ours < best generic baseline
    piv = bl.pivot_table(index="building_id", columns="model", values="f1")
    best_gen = piv[GEN].max(axis=1)
    M("NBldgDecline", int((piv[PT] < best_gen).sum()))
    M("NBldgDeclineHOW", int((piv[PT] < piv[HW]).sum()))


