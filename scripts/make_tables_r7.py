def check_consistency(fs):
    """2x2 cell means must reproduce the simple-effect estimates exactly."""
    c = fs[(fs["metric"] == "f1") & (fs["family"] == "cell")].set_index("contrast")["estimate"]
    se = fs[(fs["metric"] == "f1") & (fs["family"] == "simple")].set_index("contrast")["estimate"]
    assert abs((c[PT] - c[HW]) - se["PatchTST(HoW) - HOW(HoW)  [backbone | HoW]"]) < 1e-9
    assert abs((c[PT] - c[PTG]) - se["PatchTST(HoW) - PatchTST(global)  [scoring | PatchTST]"]) < 1e-9
    assert abs((c[HW] - c[HWG]) - se["HOW(HoW) - HOW(global)  [scoring | HOW]"]) < 1e-9
    print("factorial cells and contrasts consistent")


